export function formatMemories(memories) {
  if (!memories.length) return '';
  return `\n\n# 2人が保存に同意した過去の話し合いのメモ（必要なときだけ自然に触れる）\n${memories
    .map((m) => `- ${m.text}`)
    .join('\n')}`;
}

export function formatAnswers(questions, answers) {
  return questions
    .map((q) => `Q. ${q.text}\nA. ${(answers[q.id] || '').trim() || '（未回答）'}`)
    .join('\n\n');
}
